    @Test
    fun tzidsInDescendingAndShuffledOrder() {
        val names = collidingNames(17)
        assertEquals(1, names.map { it.hashCode() }.toSet().size)
        zonesInOrder(names.sortedDescending())
        zonesInOrder(names.shuffled(Random(17)))
    }

    // UIDs, TZIDs and component names with one hashCode through iTIP, fingerprints and their diff, the
    // series helpers, the feed publisher and the fixups; none of them keys a hash table by strings from the input. The
    // calendar has a property after its children, so every edit of it keeps their positions (that was quadratic too).
    @Test
    fun inputKeysWithOneHashCode() {
        val names = collidingNames(15)
        fun calendar(method: String?) = calendar {
            if (method != null) line("METHOD:$method")
            for (name in names) {
                line("BEGIN:VTIMEZONE")
                line("TZID:$name")
                line("BEGIN:STANDARD")
                line("DTSTART:19700101T000000")
                line("TZOFFSETTO:+0100")
                line("END:STANDARD")
                line("END:VTIMEZONE")
            }
            line("X-WR-CALNAME:a property after the children, so the calendar keeps the positions of its children")
            for (name in names) {
                line("BEGIN:VEVENT")
                line("UID:$name")
                line("DTSTAMP:20260101T000000Z")
                line("SEQUENCE:1")
                line("DTSTART;TZID=$name:20260101T090000")
                line("END:VEVENT")
                line("BEGIN:$name")
                line("END:$name")
            }
        }
        val bytes = calendar(null)
        val store = ICal.parse(bytes).calendars.single()
        val fingerprints = ICal.fingerprints(bytes)
        assertEquals(3 * names.size, fingerprints.diff(fingerprints).unchangedCount)
        assertEquals(3 * names.size, fingerprints.diff(ICal.fingerprints(calendar("PUBLISH"))).unchangedCount)
        for (method in listOf("REQUEST", "CANCEL", "PUBLISH")) {
            val message = ICal.parse(calendar(method)).calendars.single()
            val result = ITip.apply(store, message)
            assertEquals(ITipOutcome.Applied, result.outcome, method)
            assertEquals(names.size, result.calendar.events.size, method)
        }
        val parts = Series.splitByUid(store)
        assertEquals(2 * names.size, parts.size)
        assertEquals(1, parts.first().component.components("VTIMEZONE").size)
        assertEquals(names.size, Series.merge(*parts.toTypedArray()).component.components("VTIMEZONE").size)
        val published = FeedPublisher(FIXED_CLOCK).publish(store, store)
        assertEquals(names.size, published.events.size)
        assertEquals(store.component, Fixups.windowsTzids.apply(store).calendar.component)
    }

    // As many VTIMEZONEs and events as [tzids], in that order: the zones of the file, the cache of the occurrences and
    // the VTIMEZONE resolver each meet the TZIDs in this order.
    private fun zonesInOrder(tzids: List<String>) {
        val bytes = calendar {
            for (tzid in tzids) {
                line("BEGIN:VTIMEZONE")
                line("TZID:$tzid")
                line("BEGIN:STANDARD")
                line("DTSTART:19700101T000000")
                line("TZOFFSETTO:+0100")
                line("END:STANDARD")
                line("END:VTIMEZONE")
            }
            for (tzid in tzids) {
                line("BEGIN:VEVENT")
                line("UID:$tzid")
                line("DTSTART;TZID=$tzid:20260101T090000")
                line("END:VEVENT")
            }
        }
        val calendar = ICal.parse(bytes).calendars.single()
        val start = Instant.parse("2026-01-01T08:00:00Z")
        assertEquals(tzids.size, calendar.occurrences(FROM, TO).count { it.start == start })
        val zones = TimeZoneResolvers.vtimezone(calendar)
        assertEquals(tzids.size, calendar.events.count { it.component[Properties.DTSTART]!!.toInstant(zones) == start })
    }

    // 2^[bits] names of `AL` and `B-` blocks: the two blocks have the same String.hashCode on every platform.
    private fun collidingNames(bits: Int): List<String> = List(1 shl bits) { value ->
        buildString {
            append("X-")
            for (block in 0 until bits) append(if (value shr block and 1 == 0) "AL" else "B-")
        }
    }

    // Runs every consumer over the input: the tree, both writers, fingerprints, a selective parse, and for each calendar
    // canonical form, validation, lint and the occurrences of a year.
    private fun exercise(bytes: ByteArray): ParseResult {
        val result = ICal.parse(bytes)
        ICal.writer().encodeToByteArray(result.components)
        ICal.writer(WriteOptions.builder().apply { byteStable = false }.build()).encodeToByteArray(result.components)
        ICal.fingerprints(bytes)
        ICal.parser(ParseOptions.builder().apply { selection = Selection.Schedule }.build()).parse(bytes)
        val limits = RecurrenceLimits.builder().maxOccurrences(10_000).build()
        val options = OccurrenceOptions.builder()
            .recurrence(RecurrenceOptions.builder().limits(limits).build())
            .build()
        for (calendar in result.calendars) {
            Canonical.canonicalize(calendar)
            Validator.validate(calendar)
            Linter.lint(calendar)
            calendar.occurrences(FROM, TO, options).take(10_000).count()
        }
        return result
    }

    private fun depth(root: ICalComponent): Int {
        var deepest = 0
        val pending = ArrayList<Pair<ICalComponent, Int>>()
        pending += root to 1
        while (pending.isNotEmpty()) {
            val (component, level) = pending.removeAt(pending.size - 1)
            deepest = maxOf(deepest, level)
            for (child in component.components) pending += child to level + 1
        }
        return deepest
    }

    private fun calendar(body: StringBuilder.() -> Unit): ByteArray {
        val text = StringBuilder()
        text.line("BEGIN:VCALENDAR")
        text.line("VERSION:2.0")
        text.line("PRODID:-//ics-mp//hostile//EN")
        text.body()
        text.line("END:VCALENDAR")
        return text.toString().encodeToByteArray()
    }

    private fun event(body: StringBuilder.() -> Unit): ByteArray = calendar {
        line("BEGIN:VEVENT")
        line("UID:x")
        line("DTSTAMP:20260101T000000Z")
        body()
        line("END:VEVENT")
    }

    private fun StringBuilder.line(text: String) {
        append(text).append("\r\n")
    }

    private fun Int.pad(): String = toString().padStart(2, '0')

    private companion object {
        val FROM = Instant.parse("2026-01-01T00:00:00Z")
        val TO = Instant.parse("2027-01-01T00:00:00Z")
        val FIXED_CLOCK = object : Clock {
            override fun now(): Instant = Instant.parse("2026-06-01T00:00:00Z")
        }
    }
