    @Test
    fun iTipWithThousandsOfAttendeesAndInstances() {
        val request = ICal.parse(
            calendar {
                line("METHOD:REQUEST")
                line("BEGIN:VEVENT")
                line("UID:big")
                line("DTSTAMP:20260101T000000Z")
                line("DTSTART:20260101T090000Z")
                line("RRULE:FREQ=MINUTELY;COUNT=5000")
                line("SEQUENCE:0")
                line("ORGANIZER:mailto:boss@example.com")
                repeat(10_000) { line("ATTENDEE;PARTSTAT=NEEDS-ACTION:mailto:a$it@example.com") }
                line("END:VEVENT")
            },
        ).calendars.single()
        val stored = ITip.apply(VCalendar.builder().build(), request).calendar
        assertEquals(SenderCheck.Matches, IMip.checkSender(request, "mailto:boss@example.com"))
        val reply = ICal.parse(
            calendar {
                line("METHOD:REPLY")
                line("BEGIN:VEVENT")
                line("UID:big")
                line("DTSTAMP:20260101T000000Z")
                line("SEQUENCE:0")
                line("ATTENDEE;PARTSTAT=ACCEPTED:mailto:a9999@example.com")
                line("END:VEVENT")
            },
        ).calendars.single()
        val replied = ITip.apply(stored, reply).calendar
        assertEquals(10_000, replied.events.single().attendees.size)
        val cancel = ICal.parse(
            calendar {
                line("METHOD:CANCEL")
                repeat(2_000) {
                    line("BEGIN:VEVENT")
                    line("UID:big")
                    line("DTSTAMP:20260101T000000Z")
                    line("SEQUENCE:1")
                    val minute = 9 * 60 + it
                    line(
                        "RECURRENCE-ID:202601${(1 + minute / 1440).pad()}T${(minute % 1440 / 60).pad()}${(minute % 60).pad()}00Z",
                    )
                    line("END:VEVENT")
                }
            },
        ).calendars.single()
        val cancelled = ITip.apply(replied, cancel).calendar
        assertEquals(2_000, cancelled.events.single().component.properties("EXDATE").size)
    }

