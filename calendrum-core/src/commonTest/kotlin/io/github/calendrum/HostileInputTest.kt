// Hostile inputs, generated by code: each ends in bounded time and memory or with a limit problem and
// never throws outside the contract. The sizes are chosen so that quadratic work in any consumer runs into the test
// timeout, while linear work takes well under a second.
class HostileInputTest {
    @Test
    fun unclosedNestedBeginsStopAtTheDepthLimit() {
        val bytes = calendar { repeat(100_000) { line("BEGIN:X-NEST") } }
        val result = exercise(bytes)
        assertEquals(1, result.problemCount(ProblemCode.TooDeep))
        assertTrue(depth(result.components.single()) <= 16)
        val untrusted = ICal.parser(ParseOptions.Untrusted).parse(bytes)
        assertTrue(depth(untrusted.components.single()) <= 8)
    }

    @Test
    fun aMillionShortPropertiesAreReadOrCutAtTheLineLimit() {
        val bytes = event { repeat(1_000_000) { line("X-A:1") } }
        val result = exercise(bytes)
        assertEquals(1_000_000 + 2, result.calendars.single().component.components.single().properties.size)
        // The line limit of ParseOptions.Untrusted, without its two-second budget (a debug Native build under load is slower).
        val limits = ParseLimits.builder().maxLines(ParseOptions.Untrusted.limits.maxLines).build()
        val untrusted = ICal.parser(ParseOptions.builder().apply { this.limits = limits }.build()).parse(bytes)
        assertEquals(1, untrusted.problemCount(ProblemCode.TooManyLines))
        assertTrue(untrusted.isTruncated)
    }

    @Test
    fun longParametersAndLongFoldedLinesAreBounded() {
        val parameters = event {
            append("X-P")
            repeat(20_000) { append(";P").append(it).append("=v") }
            line(";LONG=" + "a".repeat(60_000) + ":value")
        }
        val result = exercise(parameters)
        assertEquals(20_001, result.calendars.single().events.single().component.property("X-P")!!.parameters.size)
        assertEquals(1, ICal.parser(ParseOptions.Untrusted).parse(parameters).problemCount(ProblemCode.LineTooLong))
        val folded = event {
            append("DESCRIPTION:")
            repeat(9 * 1024 * 1024 / 73) { append("b".repeat(73)).append("\r\n ") }
            line("end")
        }
        val cut = exercise(folded)
        assertEquals(1, cut.problemCount(ProblemCode.LineTooLong))
        assertEquals(null, cut.calendars.single().events.single().component.property("DESCRIPTION"))
    }

    @Test
    fun combinatorialAndEndlessRulesEndAtTheirLimits() {
        val limits = RecurrenceLimits.builder().maxOccurrences(20_000).maxIterationsWithoutMatch(500).build()
        val rules = listOf(
            "FREQ=YEARLY;BYMONTH=${(1..12).joinToString(",")};BYWEEKNO=${(1..53).joinToString(",")};" +
                "BYYEARDAY=${(1..366).joinToString(",")};BYMONTHDAY=${(1..31).joinToString(",")};" +
                "BYDAY=MO,TU,WE,TH,FR,SA,SU;BYHOUR=${(0..23).joinToString(",")};" +
                "BYMINUTE=${(0..59).joinToString(",")};BYSECOND=${(0..60).joinToString(",")}",
            "FREQ=YEARLY;BYDAY=MO,TU,WE,TH,FR,SA,SU;BYHOUR=${(0..23).joinToString(",")};" +
                "BYMINUTE=${(0..59).joinToString(",")};BYSECOND=${(0..59).joinToString(",")};" +
                "BYSETPOS=${(1..366).joinToString(",")},${(-366..-1).joinToString(",")};UNTIL=99991231T235959Z",
            "FREQ=SECONDLY;COUNT=2147483647",
            "FREQ=DAILY;BYSETPOS=${"1,".repeat(500_000)}1",
            "FREQ=YEARLY;BYYEARDAY=${"1,".repeat(500_000)}1;BYWEEKNO=${"1,".repeat(500_000)}1;" +
                "BYHOUR=${(0..23).joinToString(",")};BYMINUTE=${(0..59).joinToString(",")}",
            "FREQ=MONTHLY;BYDAY=${"1MO,".repeat(500_000)}1MO",
            "FREQ=SECONDLY;INTERVAL=1;UNTIL=99991231T235959Z",
            "FREQ=YEARLY;BYMONTH=2;BYMONTHDAY=30",
            "FREQ=MINUTELY;BYMONTH=2;BYMONTHDAY=30;BYHOUR=1",
        )
        for (rule in rules) {
            val sink = ArrayList<Problem>()
            val options = RecurrenceOptions.builder().limits(limits).problemListener(ProblemListener { sink += it })
                .build()
            val event = ICal.parse(
                event {
                    line("DTSTART:20260101T000000Z")
                    line("RRULE:$rule")
                },
            ).calendars.single().events.single()
            val count = Sequence { event.recurrenceSet!!.iterator(options) }.count()
            assertTrue(count <= 20_000, rule)
            val codes = sink.map { it.code }.toSet()
            assertTrue(
                ProblemCode.RecurrenceLimitReached in codes || ProblemCode.RecurrenceNoMatch in codes,
                "$rule: $count, $codes",
            )
        }
    }

    @Test
    fun aTimeZoneWithThousandsOfEndlessObservancesIsCut() {
        val bytes = calendar {
            line("BEGIN:VTIMEZONE")
            line("TZID:Hostile/Daily")
            repeat(5_000) {
                line(if (it % 2 == 0) "BEGIN:STANDARD" else "BEGIN:DAYLIGHT")
                line("DTSTART:16010101T0${it % 10}0000")
                line("RRULE:FREQ=DAILY")
                line("TZOFFSETFROM:+0${it % 10}00")
                line("TZOFFSETTO:+0${(it + 1) % 10}00")
                line(if (it % 2 == 0) "END:STANDARD" else "END:DAYLIGHT")
            }
            line("END:VTIMEZONE")
            line("BEGIN:VTIMEZONE")
            line("TZID:Hostile/Dates")
            line("BEGIN:STANDARD")
            line("DTSTART:19700101T000000")
            append("RDATE:")
            repeat(150_000) {
                append(if (it == 0) "" else ",").append(19700102 + it / 10 % 28).append("T0").append(it % 10)
                append("0000")
            }
            line("")
            line("TZOFFSETFROM:+0100")
            line("TZOFFSETTO:+0200")
            line("END:STANDARD")
            line("END:VTIMEZONE")
            line("BEGIN:VTIMEZONE")
            line("TZID:Hostile/Many")
            repeat(100_000) {
                line("BEGIN:STANDARD")
                line("DTSTART:${LocalDate.fromEpochDays(-60_000 + it).toString().replace("-", "")}T000000")
                line("TZOFFSETTO:+0${1 + it % 2}00")
                line("END:STANDARD")
            }
            line("END:VTIMEZONE")
            line("BEGIN:VTIMEZONE")
            line("TZID:Hostile/Hours")
            for ((kind, from, to) in listOf(
                Triple("STANDARD", "+0200", "+0100"),
                Triple("DAYLIGHT", "+0100", "+0200"),
            )) {
                line("BEGIN:$kind")
                line("DTSTART:20421215T000000")
                line("RRULE:FREQ=HOURLY")
                line("TZOFFSETFROM:$from")
                line("TZOFFSETTO:$to")
                line("END:$kind")
            }
            line("END:VTIMEZONE")
            line("BEGIN:VEVENT")
            line("UID:a")
            line("DTSTAMP:20260101T000000Z")
            line("DTSTART;TZID=Hostile/Daily:20260101T090000")
            line("RRULE:FREQ=HOURLY;COUNT=100")
            line("END:VEVENT")
        }
        val calendar = exercise(bytes).calendars.single()
        val sink = ArrayList<Problem>()
        val zones = TimeZoneResolvers.default(calendar)
        val context = ResolveContext(null, ProblemListener { sink += it })
        assertNull(zones.resolve("Hostile/Daily", context))
        val codes = sink.map { it.code }.toSet()
        assertTrue(ProblemCode.InvalidVTimeZone in codes && ProblemCode.UnknownTimeZone in codes, codes.toString())
        for (tzid in listOf("Hostile/Dates", "Hostile/Many", "Hostile/Hours")) {
            val zone = zones.resolve(tzid, ResolveContext.Empty)
            assertNotNull(zone, tzid)
            zone.offsetAt(Instant.parse("2026-06-01T00:00:00Z"))
            zone.offsetAt(Instant.parse("9999-06-01T00:00:00Z"))
        }
    }

