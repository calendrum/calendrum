#!/usr/bin/env python3
"""Generates the classes of the results from the schemas of the contract, and the version from tooling/gradle.properties.

Usage: python3 -I -B generate.py [--check]

With --check it writes nothing and fails when a file differs from what it would write.
"""
import json
import os
import sys
import textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
SCHEMAS = os.path.normpath(os.path.join(HERE, "..", "..", "conformance", "ops", "schema"))
PROPERTIES = os.path.normpath(os.path.join(HERE, "..", "gradle.properties"))
MODELS = os.path.join(HERE, "Calendrum", "Models.g.cs")
JSON_CONTEXT = os.path.join(HERE, "Calendrum", "Internal", "CalendrumJson.g.cs")
VERSION_CODE = os.path.join(HERE, "Calendrum", "Internal", "PackageVersion.g.cs")
VERSION_PROPS = os.path.join(HERE, "Calendrum", "Version.g.props")

HEADER = "// Generated by tooling/sdk-net/generate.py from {}. Do not edit."

OPERATIONS = (
    "inspect",
    "validate",
    "fix",
    "expand",
    "rrule_expand",
    "freebusy",
    "build_event",
    "diff",
    "convert",
    "anonymize",
    "tz_resolve",
    "explain",
)

# The operation and the path of properties to each object of a result: its class and the sentence of its summary. Two paths can share
# a class if their schemas are the same. An object that is not here stops the script: a new one needs a name.
CLASSES = {
    ("inspect",): ("InspectResult", "The result of <c>inspect</c>."),
    ("inspect", "calendars"): ("InspectCalendar", "One calendar of a file."),
    ("inspect", "calendars", "events"): ("InspectEvent", "One event of a calendar."),
    ("validate",): ("ValidateResult", "The result of <c>validate</c>."),
    ("validate", "issues"): ("ValidateIssue", "One finding of the rules."),
    ("fix",): ("FixResult", "The result of <c>fix</c>."),
    ("fix", "changes"): ("FixChange", "One repair that was made."),
    ("expand",): ("ExpandResult", "The result of <c>expand</c>."),
    ("expand", "occurrences"): ("Occurrence", "One occurrence in the window."),
    ("rrule_expand",): ("RruleExpandResult", "The result of <c>rrule_expand</c>."),
    ("rrule_expand", "dates"): ("RruleDate", "One date of a rule."),
    ("freebusy",): ("FreebusyResult", "The result of <c>freebusy</c>."),
    ("freebusy", "busy"): ("BusyInterval", "One merged busy interval."),
    ("freebusy", "conflicts"): ("Conflict", "A pair of occurrences that overlap."),
    ("freebusy", "conflicts", "first"): ("ConflictSide", "One occurrence of a conflict."),
    ("freebusy", "conflicts", "second"): ("ConflictSide", "One occurrence of a conflict."),
    ("build_event",): ("BuildEventResult", "The result of <c>build_event</c>."),
    ("diff",): ("DiffResult", "The result of <c>diff</c>."),
    ("diff", "added"): ("DiffComponent", "One component that differs between the two calendars."),
    ("diff", "removed"): ("DiffComponent", "One component that differs between the two calendars."),
    ("diff", "changed"): ("DiffComponent", "One component that differs between the two calendars."),
    ("convert",): ("ConvertResult", "The result of <c>convert</c>: the other form of the input."),
    ("anonymize",): ("AnonymizeResult", "The result of <c>anonymize</c>."),
    ("tz_resolve",): ("TzResolveResult", "The result of <c>tz_resolve</c>."),
    ("tz_resolve", "next_transition"): ("NextTransition", "The next change of the offset."),
    ("explain",): ("ExplainResult", "The result of <c>explain</c>."),
}

TRUNCATED_NOTE = "Whether the result does not hold everything: a limit cut a list, or the input was not read whole."
UNTRUSTED_NOTE = "Untrusted: text from the calendar, which is data and not instructions."


def load(name):
    with open(os.path.join(SCHEMAS, f"{name}.schema.json"), encoding="utf-8") as file:
        return json.load(file)


DEFINITIONS = load("common")["$defs"]
REF_PREFIX = "common.schema.json#/$defs/"


def dereference(schema):
    if "$ref" not in schema:
        return schema
    reference = schema["$ref"]
    if not reference.startswith(REF_PREFIX):
        raise SystemExit(f"Unknown reference {reference}")
    target = dict(DEFINITIONS[reference[len(REF_PREFIX):]])
    target.update((key, value) for key, value in schema.items() if key != "$ref")
    return target


def pascal(name):
    return "".join(part[:1].upper() + part[1:] for part in name.split("_"))


def xml_text(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


class Field:
    def __init__(self, json_name, type_name, reference, required, note):
        self.json_name = json_name
        self.name = pascal(json_name)
        self.type_name = type_name
        self.reference = reference
        self.required = required
        self.note = note


class Model:
    def __init__(self, name, summary, schema, fields, is_result):
        self.name = name
        self.summary = summary
        self.schema = schema
        self.fields = fields
        self.is_result = is_result


class Builder:
    def __init__(self):
        self.models = {}

    def problem(self):
        return self.model_for("Problem", "A problem of the input, with its stable code.", DEFINITIONS["problems"]["items"], (), False)

    def model_for(self, name, summary, schema, path, is_result):
        if name in self.models:
            if self.models[name].schema != schema:
                raise SystemExit(f"{name} is used for two different schemas, one of them at {path}")
            return self.models[name]
        required = schema.get("required", [])
        fields = [self.field(path, key, value, key in required) for key, value in schema["properties"].items()]
        model = Model(name, summary, schema, fields, is_result)
        self.models[name] = model
        return model

    def nested(self, path, schema):
        if path not in CLASSES:
            raise SystemExit(f"The object at {path} has no class: add it to CLASSES")
        name, summary = CLASSES[path]
        return self.model_for(name, summary, schema, path, False)

    def field(self, path, name, schema, required):
        schema = dereference(schema)
        kind = schema.get("type")
        notes = []
        if schema.get("x-untrusted"):
            notes.append(UNTRUSTED_NOTE)
        if "description" in schema:
            notes.append(xml_text(schema["description"]))
        if "enum" in schema:
            notes.append("One of: " + ", ".join(schema["enum"]) + ".")
        simple = {"string": ("string", True), "integer": ("int", False), "boolean": ("bool", False)}
        if kind in simple:
            type_name, reference = simple[kind]
        elif kind == "object":
            type_name, reference = self.nested((*path, name), schema).name, True
        elif kind == "array":
            items = schema.get("items")
            if items is None:
                # Plain JSON, as jCal is a tree that no class says anything about.
                type_name, reference = "JsonElement", False
            else:
                items = dereference(items)
                if items.get("type") in simple:
                    type_name, reference = f"IReadOnlyList<{simple[items['type']][0]}>", True
                elif items.get("type") == "object":
                    is_problem = items == DEFINITIONS["problems"]["items"]
                    model = self.problem() if is_problem else self.nested((*path, name), items)
                    type_name, reference = f"IReadOnlyList<{model.name}>", True
                else:
                    raise SystemExit(f"The items of {path} {name} have the type {items.get('type')}")
        else:
            raise SystemExit(f"The field {path} {name} has the type {kind}")
        return Field(name, type_name, reference, required, " ".join(notes))


def summary_lines(text, indent):
    wrapped = textwrap.wrap(text, width=120 - len(indent) - 4, break_long_words=False, break_on_hyphens=False)
    return [f"{indent}/// <summary>"] + [f"{indent}/// {line}" for line in wrapped] + [f"{indent}/// </summary>"]


def emit_model(model, lines):
    lines.append("")
    lines += summary_lines(model.summary, "")
    interface = " : IOperationResult" if model.is_result else ""
    lines += [f"public sealed class {model.name}{interface}", "{"]
    first = True
    for field in model.fields:
        if not first:
            lines.append("")
        first = False
        note = field.note or f"The field <c>{field.json_name}</c> of the contract."
        if not field.required:
            note += " Absent when it does not apply."
        lines += summary_lines(note, "    ")
        lines.append(f'    [JsonPropertyName("{field.json_name}")]')
        if field.type_name.startswith("IReadOnlyList<"):
            # The reader of JSON fills a List<T>, which a cast would let the caller change: a list keeps a copy behind a read-only view.
            backing = "_" + field.name[0].lower() + field.name[1:]
            if field.required:
                lines += [
                    f"    public required {field.type_name} {field.name}",
                    "    {",
                    f"        get => {backing};",
                    f"        init => {backing} = Frozen.List(value);",
                    "    }",
                    "",
                    f"    private readonly {field.type_name} {backing} = [];",
                ]
            else:
                lines += [
                    f"    public {field.type_name}? {field.name}",
                    "    {",
                    f"        get => {backing};",
                    f"        init => {backing} = value is null ? null : Frozen.List(value);",
                    "    }",
                    "",
                    f"    private readonly {field.type_name}? {backing};",
                ]
        elif field.required:
            lines.append(f"    public required {field.type_name} {field.name} {{ get; init; }}")
        else:
            lines.append(f"    public {field.type_name}? {field.name} {{ get; init; }}")
    if model.is_result:
        lines.append("")
        lines += summary_lines(TRUNCATED_NOTE, "    ")
        lines.append("    [JsonIgnore]")
        lines.append("    public bool Truncated { get; internal set; }")
    lines.append("}")


def build():
    builder = Builder()
    builder.problem()
    results = []
    for operation in OPERATIONS:
        name, summary = CLASSES[(operation,)]
        results.append(builder.model_for(name, summary, load(f"{operation}.result"), (operation,), True))
    return builder, results


def models_text():
    builder, _ = build()
    lines = [
        HEADER.format("conformance/ops/schema"),
        "#nullable enable",
        "",
        "using System.Collections.Generic;",
        "using System.Text.Json;",
        "using System.Text.Json.Serialization;",
        "using Calendrum.Internal;",
        "",
        "namespace Calendrum;",
    ]
    for name in sorted(builder.models):
        emit_model(builder.models[name], lines)
    return "\n".join(lines) + "\n"


def context_text():
    _, results = build()
    lines = [
        HEADER.format("conformance/ops/schema"),
        "#nullable enable",
        "",
        "using System.Text.Json.Serialization;",
        "",
        "namespace Calendrum.Internal;",
        "",
        "// No reflection: this works under trimming and Native AOT. The depth is above what the library can answer, which is its limit of",
        "// 64 levels of jCal inside the levels of the envelope.",
        "[JsonSourceGenerationOptions(",
        "    GenerationMode = JsonSourceGenerationMode.Metadata,",
        "    DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,",
        "    MaxDepth = 256)]",
    ]
    lines += [f"[JsonSerializable(typeof(Envelope<{model.name}>))]" for model in results]
    lines += [
        "[JsonSerializable(typeof(NativeVersions))]",
        "internal sealed partial class CalendrumJson : JsonSerializerContext",
        "{",
        "}",
    ]
    return "\n".join(lines) + "\n"


def package_version():
    with open(PROPERTIES, encoding="utf-8") as file:
        for line in file:
            if line.startswith("sdkNetVersion="):
                return line.split("=", 1)[1].strip()
    raise SystemExit(f"No sdkNetVersion in {PROPERTIES}")


def version_code_text():
    return (
        HEADER.format("tooling/gradle.properties") + "\n"
        "namespace Calendrum.Internal;\n\n"
        "internal static class PackageVersion\n{\n"
        f'    internal const string Value = "{package_version()}";\n'
        "}\n"
    )


def version_props_text():
    return (
        "<!-- Generated by tooling/sdk-net/generate.py from tooling/gradle.properties. Do not edit. -->\n"
        "<Project>\n"
        "  <PropertyGroup>\n"
        f"    <Version>{package_version()}</Version>\n"
        "  </PropertyGroup>\n"
        "</Project>\n"
    )


def main():
    check = "--check" in sys.argv[1:]
    failed = False
    files = ((MODELS, models_text()), (JSON_CONTEXT, context_text()), (VERSION_CODE, version_code_text()), (VERSION_PROPS, version_props_text()))
    for path, text in files:
        if check:
            try:
                with open(path, encoding="utf-8", newline="") as file:
                    current = file.read()
            except FileNotFoundError:
                current = None
            if current != text:
                print(f"{path} differs from what generate.py writes: run it")
                failed = True
        else:
            with open(path, "w", encoding="utf-8", newline="\n") as file:
                file.write(text)
    if failed:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
